package com.corewall.qaqc.v2.pdf

/**
 * سلّم التقريب لمساحة V2 — **مصدر واحد** للجدولة وللرسم.
 *
 * الجدول ده كان متكرّر: نسخة في [V2TileScheduler] بتقرّر تطلب أنهي بلاطة،
 * ونسخة في [PdfWorkspaceView] بتقرّر ترسمها بأنهي مقاس. أي تعديل في واحدة
 * من غير التانية بيخلّي البلاطة تترسم بمقاس غير اللي اترندرت بيه — يعني
 * الرسمة تطلع مزحلقة أو مكرّرة، من غير أي خطأ في البناء يلفت النظر.
 *
 * السلّم بيوصل ٦٤ بكسل لكل نقطة. البلاطة ثابتة ٣٨٤ بكسل مهما كان
 * المستوى، فتكلفة رندر البلاطة الواحدة ما بتتغيّرش؛ اللي بيزيد هو عددها
 * على الصفحة، وإحنا بنطلب المرئي منها بس.
 */
internal object V2ZoomLadder {

    fun levelFor(zoom: Float): Int = when {
        zoom < 0.75f -> 0
        zoom < 1.5f -> 1
        zoom < 3f -> 2
        zoom < 6f -> 3
        zoom < 12f -> 4
        zoom < 24f -> 5
        zoom < 48f -> 6
        else -> 7
    }

    fun scaleFor(level: Int): Float = when (level.coerceIn(0, 7)) {
        0 -> 0.5f
        1 -> 1f
        2 -> 2f
        3 -> 4f
        4 -> 8f
        5 -> 16f
        6 -> 32f
        else -> 64f
    }
}
