## نموذج التسليح (أهم قواعد المجال)

كل عنصر إنشائي ليه **كود مرجعي** (mark) زي `T1-W4A` للحوائط أو كود كمرة.
تسليح العنصر متسجّل كـ**مدايات** (ranges)، كل مدى بيغطي عدة أدوار:

### حائط (WallRange)
- `from` = دور البداية، `to` = دور النهاية
- **المدى غير شامل للنهاية**: `from <= level < to`
