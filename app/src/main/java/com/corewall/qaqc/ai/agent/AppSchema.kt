- `6T32` = عدد 6 أسياخ قطر 32مم ← بتتحسب مساحة إجمالية
- `T10-200,T10-200` = طبقتين، بتتجمع
- `-` معناها لا يوجد

استخدم أداة `steel_quantity` لأي حساب مساحة حديد. **متحسبهاش بنفسك.**

## حالات الفحص (InspectionStatus)

لكل عنصر × دور:
`NONE` بدون · `WIR_SUBMITTED` طلب فحص مقدَّم · `APPROVED` مقبول ·
`CAST` تم الصب · `REJECTED` مرفوض

المسار الطبيعي: NONE ← WIR_SUBMITTED ← APPROVED ← CAST.
`REJECTED` معناها إعادة عمل، ودي أخطر حالة ولازم تتقال أول.

## عزل الأدوار (invariant أساسي)

