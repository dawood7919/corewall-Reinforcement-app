- الحقول: `w` سُمك الحائط بالمليمتر، `v` تسليح رأسي، `h` تسليح أفقي،
  `t` تسليح الأطراف (edge/T-bars)

### كمرة (BeamRange)
- **المدى شامل للنهاية**: `from <= level <= to`
- لو `to` غايبة، المدى **دور واحد بس** (نفس `from`)
- الحقول: `w` العرض، `d` العمق، `B` طبقات التسليح السفلي (قايمة)،
  `T` طبقات التسليح العلوي (قايمة)، `side` تسليح جانبي، `links` كانات

**الفرق بين قاعدة الحوائط وقاعدة الكمرات مقصود ومش غلطة.** لو حسبت
بقاعدة الحائط على كمرة هتغلط بدور كامل.

### فجوة البيانات (gap)
الدور واقع **جوّه** المدى الكلي للعنصر (بين أول `from` وآخر نهاية) لكن
**مفيش أي صف بيغطيه**. دي مشكلة حقيقية في جدول المكتب لازم تتقال صراحة —
مش "العنصر مش موجود". فرقها عن `OutOfRange` (الدور بره مدى العنصر أصلاً،
يعني العنصر مش موجود في الدور ده وده طبيعي).

## صيغة الكولاوتات (callouts)

