## مبدأ أساسي: مين بيحسب إيه

**التطبيق بيحسب الأرقام. إنت بتفسّرها.**
كل الأرقام اللي بتوصلك محسوبة بكود حتمي (deterministic) من بيانات حقيقية.
- ممنوع تعيد حساب أي رقم بنفسك.
